"""Build tt-examples-v0, worked examples from tt-metal's programming examples at the pin (OQ-083 (b), 2026-10-25).

Usage:

    uv run tools/build_tt_examples.py fetch --dest <dir> [--spec <file>]
    uv run tools/build_tt_examples.py build --tree <dir> [--out <dir>] [--spec <file>]
    uv run tools/build_tt_examples.py check [--tree <dir>] [--out <dir>] [--spec <file>]

The owner's answer to OQ-083 of 2026-10-25, option (b): tt-pairs-v0 is a
development set, and prompt work steered by its outcomes is allowed. The
build-error report of 2026-10-25 shows the models writing the TT-Metalium
host API from memory, an older one, so a prompt may carry complete host
programs at the pin (lassi.core.stages, the recipe's `examples` section).

The spec (default assets/examples/tt-examples-v0/spec.yaml) names the pack,
the pin, the data set spec it is held to (tools/build_tt_train.py's
dataset.yaml, whose root, include and exclude lists, held-out suite, and
rule parameters it reads), and, in order, each example directory with every
code file (.cpp, .hpp, .h) under it: the host program first, then its
kernels (under kernels/), sorted. The tree is the pinned tt-metal at the
pin's COMMIT: an install ($LASSI_TOOLCHAINS/<PREFIX_NAME>, whose
lassi-install.txt names the pin) or a directory `fetch` filled, whose
lassi-fetch.txt names the commit and the pack. Any other tree is refused.

- fetch downloads, at exactly the pin's commit, every regular file under a
  listed directory and under each held item's example directory (which
  rule 4 reads), listed through the GitHub git trees API and checked
  against its git blob sha1, into `--dest`, outside this repository.
- build writes the fragments, each file at <directory>/<path> with exactly
  the tree's bytes, and MANIFEST.yaml (lassi.prompts.examples) under
  `--out` (default: the spec's directory). Only the spec and the manifest
  are tracked; the fragments are gitignored, as no tt-metal text is.
- check verifies the fragments under `--out` against the manifest
  (lassi.prompts.examples check_pack) and the manifest's spec_sha256
  against the spec; with --tree it also builds in memory and compares the
  manifest. Status 1 names each difference; nothing is written.

Agent Rule 5, the rules build enforces: each listed directory is in the
data set's include list (so never one of its exclusions: the five Tier A
items' directories and their duplicates), and the data set's own checks
hold (build_tt_train.py rule 1); no file holds a run of run_lines
consecutive non-blank lines of a tracked Tier A reference (rule 3, on each
file and on the example's FILE blocks); and no file is byte-identical to a
file of a Tier A example directory or shares at least near_copy of its runs
with those files (rule 4), whose directories the tree must hold. The same
tree and spec always give the same bytes.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools"))

import build_tt_train as train  # noqa: E402

from lassi.bench import load_suite  # noqa: E402
from lassi.prompts import examples as pack  # noqa: E402
from lassi.toolchains import pins  # noqa: E402

DEFAULT_SPEC = REPO / "assets" / "examples" / "tt-examples-v0" / "spec.yaml"
FETCH_RECORD = train.FETCH_RECORD
SPEC_KEYS = {"pack", "pin", "dataset", "examples"}
ENTRY_KEYS = {"directory", "files"}
KERNELS = "kernels/"
HEADER = (
    f"# Generated by {pack.GENERATOR} from the pinned tt-metal tree and spec.yaml beside it; do not edit.\n"
    "# Only this manifest and the spec are tracked: the fragment files beside them hold tt-metal's text and are\n"
    "# gitignored. Each listed directory is in the data set's include list, and no file holds a run of\n"
    "# run_lines lines of a tracked Tier A reference or copies a Tier A example file (Agent Rule 5; the tool's\n"
    "# docstring). sha256 is the sha256 of the lines '<sha256>  <path>' of every file in order.\n"
)


@dataclass(frozen=True)
class ExampleSpec:
    """One listed example: its directory under the data set's root, and its files in order, host program first."""

    directory: str
    files: tuple[str, ...]


@dataclass(frozen=True)
class PackSpec:
    """A checked pack spec (the module docstring); every field is required."""

    pack: str
    pin: str
    dataset: str
    examples: tuple[ExampleSpec, ...]


@dataclass(frozen=True)
class Built:
    """A built pack: the fragments {pack path: bytes} in spec order, and each example's manifest entry."""

    fragments: dict[str, bytes]
    examples: list[dict[str, Any]]


def main(argv: list[str] | None = None) -> int:
    """Run one subcommand; return 0 on success, 1 when check finds a difference, 2 on a refusal."""
    args = _parser().parse_args(argv)
    try:
        spec_path = Path(args.spec).resolve()
        spec = load_spec(spec_path)
        dataset = train.load_spec(REPO / spec.dataset)
        pin = pins.read_pin(spec.pin)
        if spec.pin != dataset.pin:
            raise ValueError(f"{spec_path} names the pin {spec.pin}, and {spec.dataset} the pin {dataset.pin}")
        if args.command == "fetch":
            count = fetch(Path(args.dest), spec, dataset, train.load_held_out(dataset), pin)
            print(f"build_tt_examples: {count} files of {pin['NAME']} at {pin['COMMIT']} in {args.dest}")
            return 0
        out = Path(args.out) if args.out else spec_path.parent
        document, built = (None, None)
        if args.tree:
            document, built = build_tree(Path(args.tree), spec_path, spec, dataset, pin)
    except (OSError, ValueError) as error:
        print(f"build_tt_examples: {error}", file=sys.stderr)
        return 2
    if args.command == "check":
        return check(out, spec_path, document)
    if document is None or built is None:
        print("build_tt_examples: build needs --tree", file=sys.stderr)
        return 2
    write_pack(out, built.fragments, document)
    print(f"build_tt_examples: {len(built.examples)} examples, {len(built.fragments)} files under {out}; "
          f"pack sha256 {document['sha256']}")
    return 0


def load_spec(path: Path) -> PackSpec:
    """Read and check a pack spec; ValueError naming the key for any missing, unknown, or malformed one."""
    data = yaml.safe_load(Path(path).read_bytes().decode("ascii"))
    if not isinstance(data, dict) or set(data) != SPEC_KEYS:
        found = sorted(data) if isinstance(data, dict) else data
        raise ValueError(f"{path}: a spec holds exactly {sorted(SPEC_KEYS)}, not {found}")
    listed = data["examples"]
    if not isinstance(listed, list) or not listed:
        raise ValueError(f"{path}: examples must be a non-empty list of {sorted(ENTRY_KEYS)}")
    entries: list[ExampleSpec] = []
    for entry in listed:
        if not isinstance(entry, dict) or set(entry) != ENTRY_KEYS or not isinstance(entry["files"], list):
            raise ValueError(f"{path}: each example holds exactly {sorted(ENTRY_KEYS)}, files a list: {entry!r}")
        entries.append(ExampleSpec(directory=str(entry["directory"]).strip("/"),
                                   files=tuple(str(item) for item in entry["files"])))
    names = [entry.directory for entry in entries]
    if len(set(names)) != len(names):
        raise ValueError(f"{path}: an example directory is listed twice")
    return PackSpec(pack=str(data["pack"]), pin=str(data["pin"]), dataset=str(data["dataset"]),
                    examples=tuple(entries))


def build(files: Mapping[str, bytes], spec: PackSpec, dataset: Any, held: Any) -> Built:
    """Return the pack built from the tree's `files` ({tree path: bytes}); ValueError for any rule it breaks."""
    for entry in spec.examples:
        if entry.directory not in dataset.include:
            why = "it is excluded there" if entry.directory in dataset.exclude else "it is not listed there"
            raise ValueError(f"{entry.directory} is not in the include list of {dataset.dataset} ({why}); a pack "
                             "lists only included examples (Agent Rule 5)")
    owners = train._owners(files, dataset)
    train._check_tier_dirs(dataset, held)
    upstream = _upstream(files, held)
    reference_runs = train._run_index(held.references, dataset.run_lines)
    upstream_runs = set(train._run_index({path: train._text(data) for path, data in upstream.items()},
                                         dataset.run_lines))
    upstream_bytes = {data: path for path, data in upstream.items()}
    fragments: dict[str, bytes] = {}
    examples: list[dict[str, Any]] = []
    for entry in spec.examples:
        owned = _owned(entry, owners, files, dataset.root)
        for path, data in owned.items():
            _check_runs(f"{entry.directory}/{path}", train._text(data), reference_runs, dataset.run_lines)
        blocks = pack.file_blocks([(path, train._text(data)) for path, data in owned.items()])
        _check_runs(f"{entry.directory} (its FILE blocks)", blocks, reference_runs, dataset.run_lines)
        tree_owned = {f"{dataset.root}/{entry.directory}/{path}": data for path, data in owned.items()}
        overlap = train._check_copies(entry.directory, tree_owned, upstream_bytes, upstream_runs, dataset)
        rows = []
        for path, data in owned.items():
            fragments[f"{entry.directory}/{path}"] = data
            rows.append({"path": f"{entry.directory}/{path}", "sha256": _sha256(data), "bytes": len(data)})
        examples.append({"name": entry.directory, "files": rows, "upstream_overlap": overlap})
    return Built(fragments=fragments, examples=examples)


def _upstream(files: Mapping[str, bytes], held: Any) -> dict[str, bytes]:
    """Return the code files of the held items' example directories; refuse a directory the tree lacks (rule 4)."""
    upstream: dict[str, bytes] = {}
    for tier, item in held.tier_dirs.items():
        found = {path: data for path, data in files.items() if train._code(path) and path.startswith(f"{tier}/")}
        if not found:
            raise ValueError(f"the tree holds no code file under {tier}, the example directory of the held item "
                             f"{item}, so the copy check (rule 4) would read nothing (Agent Rule 5); fetch it")
        upstream.update(found)
    return dict(sorted(upstream.items()))


def _owned(entry: ExampleSpec, owners: Mapping[str, str], files: Mapping[str, bytes],
           root: str) -> dict[str, bytes]:
    """Return {path in the directory: bytes} of the listed files, in spec order; refuse any that differ.

    The listed files must be exactly the code files the directory holds (the
    deepest listed directory of the data set owning each), the host program
    (outside kernels/) first and then the kernels, sorted.
    """
    base = f"{root}/{entry.directory}/"
    held = sorted(path[len(base):] for path, owner in owners.items() if owner == entry.directory)
    unlisted = [path for path in held if path not in entry.files]
    strange = [path for path in entry.files if path not in held]
    if unlisted or strange or not entry.files:
        raise ValueError(f"{entry.directory}: the spec must list exactly its code files, at least one; unlisted: "
                         f"{unlisted}, listed but no code file of it: {strange}")
    host, *kernels = entry.files
    if host.startswith(KERNELS) or kernels != sorted(kernels) or not all(path.startswith(KERNELS) for path in kernels):
        raise ValueError(f"{entry.directory}: list its host program first, then its kernels under {KERNELS}, "
                         f"sorted; got {list(entry.files)}")
    return {path: files[base + path] for path in entry.files}


def _check_runs(name: str, text: str, index: Mapping[tuple[str, ...], str], size: int) -> None:
    """Refuse a file (or FILE-block text) that holds a run of a tracked Tier A reference (rule 3)."""
    for run in train.runs(text, size):
        if run in index:
            raise ValueError(f"{name} holds the run {' | '.join(run)!r} of {index[run]}; leave its example out of "
                             "the pack (Agent Rule 5)")


def build_tree(tree: Path, spec_path: Path, spec: PackSpec, dataset: Any,
               pin: Mapping[str, str]) -> tuple[dict[str, Any], Built]:
    """Return (manifest document, built pack) for `tree`; refuse a tree that is not the pinned one."""
    check_tree(tree, pin, spec.pack)
    held = train.load_held_out(dataset)
    suite = load_suite(REPO / dataset.suite)
    if suite.commit != pin["COMMIT"]:
        raise ValueError(f"{dataset.suite} pins {suite.commit}, not {spec.pin}'s COMMIT {pin['COMMIT']}")
    built = build(train.tree_files(tree, dataset.root), spec, dataset, held)
    checks = {"dataset": spec.dataset, "dataset_sha256": _sha256((REPO / spec.dataset).read_bytes()),
              "root": dataset.root, "suite": held.suite_path, "suite_sha256": held.suite_sha256,
              "run_lines": dataset.run_lines, "near_copy": dataset.near_copy,
              "references": [{"path": path, "sha256": _sha256(text.encode("utf-8"))}
                             for path, text in held.references.items()],
              "example_dirs": [{"path": path, "item": item} for path, item in held.tier_dirs.items()]}
    document = manifest_document(built, spec, pin, spec_sha256=_sha256(spec_path.read_bytes()),
                                 spec_name=_repo_name(spec_path), checks=checks)
    return document, built


def manifest_document(built: Built, spec: PackSpec, pin: Mapping[str, str], *, spec_sha256: str, spec_name: str,
                      checks: Mapping[str, Any]) -> dict[str, Any]:
    """Return the manifest: the generator, the pack, the source, the spec, the checks, the examples, the sha256."""
    entries = [(row["path"], row["sha256"]) for example in built.examples for row in example["files"]]
    return {
        "generator": pack.GENERATOR,
        "pack": spec.pack,
        "repo": pin["URL"],
        "commit": pin["COMMIT"],
        "version": pin["VERSION"],
        "spec": spec_name,
        "spec_sha256": spec_sha256,
        "checks": dict(checks),
        "examples": built.examples,
        "sha256": pack.pack_sha256(entries),
    }


def manifest_text(document: Mapping[str, Any]) -> str:
    """Return MANIFEST.yaml: the header, then the document as block YAML in document order, plain ASCII."""
    return HEADER + yaml.safe_dump(dict(document), sort_keys=False, default_flow_style=False, width=120)


def write_pack(out: Path, fragments: Mapping[str, bytes], document: Mapping[str, Any]) -> None:
    """Write each fragment and MANIFEST.yaml under `out`, each only when its bytes changed (LF, as given)."""
    files = {**fragments, pack.MANIFEST: manifest_text(document).encode("ascii")}
    for name, data in files.items():
        path = out / name
        if not (path.is_file() and path.read_bytes() == data):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)


def check(out: Path, spec_path: Path, document: Mapping[str, Any] | None) -> int:
    """Return 0 when the fragments match the manifest, and it the spec (and the build, with --tree); else 1."""
    problems = pack.check_pack(out)
    manifest = out / pack.MANIFEST
    try:
        recorded = pack.read_manifest(manifest)
    except ValueError:
        recorded = {}
    if recorded and recorded.get("spec_sha256") != _sha256(spec_path.read_bytes()):
        problems.append(f"{manifest}: its spec_sha256 is not that of {spec_path}; rebuild the pack")
    for key in document or {}:
        if recorded and recorded.get(key) != yaml.safe_load(yaml.safe_dump(document[key])):
            problems.append(f"{manifest}: {key} differs from this build")
    for problem in problems:
        print(f"build_tt_examples: {problem}", file=sys.stderr)
    if not problems:
        print(f"build_tt_examples: {out} matches {manifest.name} (pack sha256 {recorded.get('sha256')})")
    return 1 if problems else 0


def check_tree(tree: Path, pin: Mapping[str, str], name: str) -> None:
    """Raise ValueError unless `tree` is an install of the pin or a fetch of the pin's commit for pack `name`."""
    record = tree / FETCH_RECORD
    if record.is_file():
        lines = record.read_bytes().decode("utf-8", errors="replace").splitlines()
        if lines[:1] == [pin["COMMIT"]] and len(lines) > 1 and lines[1].startswith(f"pack {name}:"):
            return
        raise ValueError(f"{record} does not name commit {pin['COMMIT']} and pack {name}; fetch the tree again "
                         "with uv run tools/build_tt_examples.py fetch")
    try:
        train.check_install_record(tree, pin)
    except ValueError as error:
        raise ValueError(f"{error}; or fetch the files with uv run tools/build_tt_examples.py fetch") from None


def fetch(dest: Path, spec: PackSpec, dataset: Any, held: Any, pin: Mapping[str, str],
          opener: train.Opener | None = None) -> int:
    """Fill `dest` with the listed and held directories' files at the pin's commit; return how many it holds.

    Each file is checked against the blob sha1 of the commit's git tree, so
    the bytes are the commit's exactly. `opener` (default: urllib) returns a
    URL's bytes; tests pass their own.
    """
    train._refuse_inside_repo(dest, "the fetch destination")
    dest.mkdir(parents=True, exist_ok=True)
    get = opener or train._urlopen
    repo, commit = train._github_repo(pin["URL"]), pin["COMMIT"]
    prefixes = [f"{dataset.root}/{entry.directory}/" for entry in spec.examples]
    prefixes += [f"{tier}/" for tier in held.tier_dirs]
    blobs = {path: blob for path, blob in train._listing(get, repo, commit, dataset.root).items()
             if any(path.startswith(prefix) for prefix in prefixes)}
    for path, blob in sorted(blobs.items()):
        train._fetch_one(get, repo, commit, dest, path, blob)
    text = (f"{commit}\npack {spec.pack}: files of {pin['URL']} at {commit} under the listed and held example "
            "directories, each checked against its git blob\n")
    (dest / FETCH_RECORD).write_bytes(text.encode("ascii"))
    return len(blobs)


def _repo_name(path: Path) -> str:
    """Return `path` relative to the repository in POSIX form, or its name when it lies outside."""
    try:
        return path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return path.name


def _sha256(data: bytes) -> str:
    """Return the sha256 hex digest of `data`."""
    return hashlib.sha256(data).hexdigest()


def _parser() -> argparse.ArgumentParser:
    """Return the command-line parser."""
    parser = argparse.ArgumentParser(prog="build_tt_examples", description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    fetch_parser = commands.add_parser("fetch", help="download the examples at the pin's commit")
    fetch_parser.add_argument("--dest", required=True, help="directory outside the repository")
    build_parser = commands.add_parser("build", help="write the fragments and the manifest")
    build_parser.add_argument("--tree", required=True, help="the pinned tt-metal tree (install or fetch)")
    check_parser = commands.add_parser("check", help="verify the fragments against the manifest")
    check_parser.add_argument("--tree", help="also build from this tree in memory and compare the manifest")
    for command in (build_parser, check_parser):
        command.add_argument("--out", help="the pack directory (default: the spec's directory)")
    for command in commands.choices.values():
        command.add_argument("--spec", default=str(DEFAULT_SPEC), help="pack spec")
    return parser


if __name__ == "__main__":
    sys.exit(main())
