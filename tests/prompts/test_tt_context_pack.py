def test_a_pack_of_several_entries_is_their_texts_joined_in_manifest_order(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    write_tree(root / "context" / "multi", {"guide.tt": "Guide text.\n", "api.tt": "int f();\n"}, GENERATOR)
    assets = load_recipe_assets({"prompts": "fixture-set", "context": ["multi"]}, root=root)
    assert prompt_assets.PACK_JOINER == "\n"
    assert assets.packs["multi"] == "Guide text.\n" + prompt_assets.PACK_JOINER + "int f();\n"


def test_a_pack_of_one_entry_is_that_entry_unchanged(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    write_tree(root / "context" / "single", {"pack.cuda": "No final newline"})
    assets = load_recipe_assets({"prompts": "fixture-set", "context": ["single"]}, root=root)
    assert assets.packs["single"] == "No final newline"


def test_a_pack_whose_entries_serve_two_languages_is_refused(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    write_tree(root / "context" / "mixed", {"guide.tt": "Guide.\n", "card.omp": "Card.\n"})
    with pytest.raises(ValueError, match="mixed"):
        load_recipe_assets({"prompts": "fixture-set", "context": ["mixed"]}, root=root)


def test_a_missing_fragment_names_the_generator_its_manifest_records(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    write_tree(root / "context" / "multi", {"guide.tt": "Guide.\n", "api.tt": "int f();\n"}, GENERATOR)
    (root / "context" / "multi" / "api.tt.txt").unlink()
    with pytest.raises(ValueError, match="build_tt_context") as caught:
        load_recipe_assets({"prompts": "fixture-set", "context": ["multi"]}, root=root)
    assert "extract_lassi_assets" not in str(caught.value), caught.value


def test_a_manifest_that_does_not_load_names_the_generator_its_text_records(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    write_tree(root / "context" / "broken", {"guide.tt": "Guide.\n"}, GENERATOR)
    manifest = root / "context" / "broken" / MANIFEST
    manifest.write_bytes(manifest.read_bytes() + b"entries: [unclosed\n")
    with pytest.raises(ValueError, match="cannot read the manifest") as caught:
        load_recipe_assets({"prompts": "fixture-set", "context": ["broken"]}, root=root)
    assert "build_tt_context" in str(caught.value) and "extract_lassi_assets" not in str(caught.value), caught.value


def test_a_missing_manifest_names_the_default_generator(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    write_tree(root / "context" / "bare", {"guide.tt": "Guide.\n"}, GENERATOR)
    (root / "context" / "bare" / MANIFEST).unlink()
    with pytest.raises(ValueError, match="cannot read the manifest") as caught:
        load_recipe_assets({"prompts": "fixture-set", "context": ["bare"]}, root=root)
    assert prompt_assets.GENERATOR in str(caught.value), caught.value


def test_only_the_committed_manifest_names_the_tt_generator(tmp_path: Path) -> None:
    root = synthetic_root(tmp_path)
    (root / "context" / PACK_NAME).mkdir(parents=True)
    shutil.copyfile(PACK_DIR / MANIFEST, root / "context" / PACK_NAME / MANIFEST)
    with pytest.raises(ValueError, match="build_tt_context"):
        load_recipe_assets({"prompts": "fixture-set", "context": [PACK_NAME]}, root=root)


@pytest.mark.parametrize("generator", ["../evil.sh", "tools/sub/x.py", "build_tt_context.py", "", 42, None],
                         ids=["outside-tools", "nested", "bare-name", "empty", "number", "null"])
def test_a_malformed_generator_is_an_error_not_a_fallback(tmp_path: Path, generator: object) -> None:
    root = synthetic_root(tmp_path)
    tree = root / "context" / "bad"
    write_tree(tree, {"guide.tt": "Guide.\n"})
    manifest = yaml.safe_load((tree / MANIFEST).read_text(encoding="ascii"))
    (tree / MANIFEST).write_bytes(yaml.safe_dump({"generator": generator, **manifest}).encode("ascii"))
    with pytest.raises(ValueError, match="generator") as caught:
        load_recipe_assets({"prompts": "fixture-set", "context": ["bad"]}, root=root)
    assert str(tree / MANIFEST) in str(caught.value), caught.value
    assert "extract_lassi_assets" not in str(caught.value), "a malformed generator never falls back to GENERATOR"


# ---------------------------------------------------------------- the committed manifest and git


def test_committed_manifest_names_the_pin_the_generator_and_two_tt_entries() -> None:
    data = (PACK_DIR / MANIFEST).read_bytes()
    assert data.isascii() and b"\r" not in data, "the manifest is plain ASCII with LF newlines"
    loaded = yaml.safe_load(data.decode("ascii"))
    assert loaded["generator"] == GENERATOR and loaded["commit"] == PIN
    assert loaded["limit_bytes"] == LIMIT_BYTES
    assert [entry["key"] for entry in loaded["entries"]] == list(KEYS)
    for entry in loaded["entries"]:
        assert len(entry["sha256"]) == 64 and entry["key"].endswith(".tt")
        for source in entry["sources"]:
            assert not source["path"].startswith("tt_metal/programming_examples/"), source
            assert len(source["sha256"]) == 64
    assert [source["path"] for source in loaded["entries"][0]["sources"]] == ["METALIUM_GUIDE.md"]
    api_sources = [source["path"] for source in loaded["entries"][1]["sources"]]
    assert api_sources[:3] == [HEAD_SOURCE, TEMPLATE_SOURCE, "tt_metal/api/tt-metalium/host_api.hpp"]
    headers = api_sources[2:] + loaded["cut_by_limit"]
    assert all(path.startswith("tt_metal/api/tt-metalium/") for path in headers), headers
    for source in loaded["entries"][1]["sources"][:2]:
        own = hashlib.sha256((REPO / source["path"]).read_bytes()).hexdigest()
        assert source["sha256"] == own, f"{source['path']} changed; regenerate the manifest"


def test_the_head_file_is_tracked_text_of_this_repository() -> None:
    data = (REPO / HEAD_SOURCE).read_bytes()
    assert data.isascii() and b"\r" not in data and data.endswith(b"\n")
    assert data.count(b"{include}") == 1 and b"{include}" in data.rstrip(b"\n").split(b"\n")[-1]
    assert not ignored(HEAD_SOURCE), "the head file is this repository's text, tracked beside the pack"


def ignored(path: str) -> bool:
    """Return True when .gitignore ignores `path` (checked against the patterns, tracked or not)."""
    done = git("check-ignore", "--quiet", "--no-index", path)
    assert done.returncode in (0, 1), f"git check-ignore failed: {done.stderr.strip()}"
    return done.returncode == 0


def test_gitignore_keeps_the_fragments_out_and_the_manifest_in() -> None:
    for name in (*(f"{key}.txt" for key in KEYS), "extra.yaml", "nested/fragment.txt"):
        assert ignored(f"assets/context/{PACK_NAME}/{name}"), f"{name} is not ignored"
    assert not ignored(f"assets/context/{PACK_NAME}/{MANIFEST}")


def test_only_the_manifest_is_tracked_in_the_pack() -> None:
    listed = git("ls-files", "--", f"assets/context/{PACK_NAME}").stdout.split()
    assert set(listed) <= {f"assets/context/{PACK_NAME}/{MANIFEST}"}, listed


