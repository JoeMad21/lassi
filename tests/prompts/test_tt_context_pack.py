def test_generated_pack_loads_as_one_text_for_the_tt_target(pack_texts: dict[str, str], tmp_path: Path) -> None:
    from lassi.core.fragments import pack_language

    root = synthetic_root(tmp_path)
    shutil.copytree(PACK_DIR, root / "context" / PACK_NAME)
    pack = load_recipe_assets({"prompts": "fixture-set", "context": [PACK_NAME]}, root=root).packs[PACK_NAME]
    assert pack == prompt_assets.PACK_JOINER.join(pack_texts.values())
    assert {pack_language(key) for key in pack_texts} == {"tt"}
    limit = yaml.safe_load((PACK_DIR / MANIFEST).read_text(encoding="ascii"))["limit_bytes"]
    assert len(pack.encode("utf-8")) <= limit


def test_generated_pack_holds_no_run_of_a_tracked_tier_a_program(pack_texts: dict[str, str]) -> None:
    tool = load_tool()
    tracked = {path.relative_to(REPO).as_posix(): path.read_bytes().decode("utf-8")
               for path in sorted((REPO / "assets" / "bench" / "tt-pairs-v0").rglob("*")) if path.is_file()}
    assert len(tracked) == 10, sorted(tracked)
    for key, text in pack_texts.items():
        hits = tool.tier_a_runs(text, tracked)
        assert not hits, f"{key} holds Tier A text: {hits[:5]}"


def test_generated_pack_holds_no_run_of_an_upstream_tier_a_file(pack_texts: dict[str, str]) -> None:
    tree = pinned_tree()
    if tree is None:
        pytest.skip("the upstream Tier A kernels are read from a tt-metal tree; set LASSI_TT_METAL_TREE")
    tool = load_tool()
    references = tool.tier_a_references(tree)
    for key, text in pack_texts.items():
        hits = tool.tier_a_runs(text, references)
        assert not hits, f"{key} holds Tier A text: {hits[:5]}"


def test_no_tracked_file_holds_a_paragraph_of_the_generated_pack(pack_texts: dict[str, str]) -> None:
    # The head file's paragraphs are this repository's own text (OQ-018 restricts only upstream text).
    own = (REPO / HEAD_SOURCE).read_bytes().decode("ascii")
    paragraphs = {block for text in pack_texts.values() for block in text.split("\n\n")
                  if len(block) >= LEAK_MIN and block.strip("\n") not in own}
    assert paragraphs, "no paragraph reaches the length the guard checks"
    hits = []
    for name in git("ls-files", "-z").stdout.split("\0"):
        path = REPO / name
        if not name or name.startswith("third_party/") or not path.is_file():
            continue
        body = path.read_bytes().decode("latin-1").replace("\r\n", "\n")
        hits.extend(name for block in paragraphs if block in body)
    assert not hits, f"tracked files hold generated pack text (OQ-018): {sorted(set(hits))}"


# ---------------------------------------------------------------- the recipes


def recipe_paths() -> list[Path]:
    """Return the six context recipes: three models, two halves each."""
    return [CONTEXT_DIR / f"{slug}-{half}.yaml" for slug in SLUGS for half in HALVES]


@pytest.mark.parametrize("path", recipe_paths(), ids=lambda path: path.stem)
def test_context_recipe_loads_and_adds_the_context_stage_for_tt(path: Path) -> None:
    data = load_recipe(path).data
    assert data["directions"] == [{"source": "cpp", "target": "tt"}], "the pack serves tt, and no cpp pack exists"
    assert data["context"] == [PACK_NAME]
    assert data["stages"] == CONTEXT_STAGES


@pytest.mark.parametrize("path", recipe_paths(), ids=lambda path: path.stem)
def test_context_recipe_passes_the_runners_context_checks(path: Path) -> None:
    # Task P17.21: tt-host-v0 holds summarize_context.txt and knowledge.txt, so it serves the pack. The runner's
    # recipe settings (the pack loaded by language) and its stage and prompt checks, which run before any directory
    # exists, accept each recipe. A full run is not started here: it needs the fetched kernels and a served model.
    recipe = load_recipe(path)
    if not generated():
        with pytest.raises(RunError, match=re.escape(GENERATOR)):
            runner_module._settings(recipe)
        return
    settings = runner_module._settings(recipe)
    assert settings.fragments == {} and set(settings.packs) == {"tt"}, "a template set with the tt pack"
    runner_module._check_stages(recipe, DEFAULT_REGISTRY, settings)


@pytest.mark.parametrize("path", recipe_paths(), ids=lambda path: path.stem)
def test_context_recipe_keeps_everything_else_of_its_sweep3_parent(path: Path) -> None:
    child = dict(load_recipe(path).data)
    parent = dict(load_recipe(SWEEP3 / path.name).data)
    for key in ("directions", "context", "stages", "project"):
        child.pop(key, None)
        parent.pop(key, None)
    assert child == parent
