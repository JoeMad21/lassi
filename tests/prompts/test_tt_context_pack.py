# A paragraph of the generated pack this long or longer may appear in no tracked file (OQ-018).
LEAK_MIN = 200


def git(*args: str) -> subprocess.CompletedProcess[str]:
    """Run git with `args` in the repository and return the finished process (text mode)."""
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True, check=False)


def write_tree(tree: Path, texts: dict[str, str], generator: str | None = None) -> None:
    """Write one `<key>.txt` per text and a MANIFEST.yaml listing each with its sha256 (and `generator`)."""
    tree.mkdir(parents=True)
    entries = []
    for key, text in texts.items():
        data = text.encode("ascii")
        (tree / f"{key}.txt").write_bytes(data)
        entries.append({"key": key, "source": "synthetic", "sha256": hashlib.sha256(data).hexdigest()})
    manifest: dict[str, Any] = {"entries": entries}
    if generator is not None:
        manifest = {"generator": generator, **manifest}
    (tree / MANIFEST).write_bytes(yaml.safe_dump(manifest, sort_keys=False).encode("ascii"))


def synthetic_root(tmp_path: Path) -> Path:
    """Return an assets root holding a one-entry synthetic fragment set named fixture-set."""
    root = tmp_path / "assets"
    write_tree(root / "prompts" / "fixture-set", {"intro": "Synthetic intro.\n"})
    return root


def generated() -> bool:
    """Return True when this checkout holds the pack's generated fragments."""
    return all((PACK_DIR / f"{key}.txt").is_file() for key in KEYS)


GENERATED_SKIP = f"the pack is not generated here; run uv run {GENERATOR} --tree <tt-metal tree at 5280a9cf>"


def load_tool() -> ModuleType:
    """Load tools/build_tt_context.py as a module."""
    spec = importlib.util.spec_from_file_location("build_tt_context_for_prompts", REPO / GENERATOR)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def pinned_tree() -> Path | None:
    """Return a tt-metal tree at the pin from LASSI_TT_METAL_TREE or $LASSI_TOOLCHAINS, or None."""
    named = os.environ.get("LASSI_TT_METAL_TREE", "")
    if named and Path(named).is_dir():
        return Path(named)
    toolchains = os.environ.get("LASSI_TOOLCHAINS", "")
    installed = Path(toolchains) / "tt-metal@5280a9cf" if toolchains else None
    return installed if installed is not None and installed.is_dir() else None


