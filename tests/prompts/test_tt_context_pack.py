"""Tests for the tt-metalium context pack: its loading, its manifest, Agent Rule 5, and the recipes that select it.

Bible: Design Principle 3 (context packs are versioned files under assets/),
Repository Layout (assets/context: generated text gitignored, only manifests
tracked, OQ-018), Agent Rule 5 (no Tier A test program enters a prompt),
Source Papers, LASSI pipeline step 2 (upstream's context stage). The owner
asked for the pack on 2026-10-23, after the RNGD sweep's C++ -> TT attempts
stalled at compile errors from calling the TT-Metalium API wrongly.

The contract these tests fix:

- A context pack may hold several entries; lassi.prompts.load_recipe_assets
  joins their texts in manifest order with PACK_JOINER, and refuses a pack
  whose entry keys end in different languages (the language a pack serves is
  the last dot-separated part of its keys, lassi.core.fragments.pack_language).
- A manifest may name the tool that generates its tree in `generator`; every
  loader error about that tree names it (default: GENERATOR, the lassi-2024
  extractor).
- A `generator` that is not a tools/ script path is an error naming the
  manifest, never a silent fallback to GENERATOR.
- assets/context/tt-metalium-5280a9cf/ is generated by
  tools/build_tt_context.py; only its MANIFEST.yaml is tracked, and the pack
  serves the language tt. The pack's own text, the reference's preamble and
  include line, is the tracked head file beside it,
  assets/context/tt-metalium-5280a9cf.head.txt, a source of host_api.tt.
- projects/lassi-demo/context/<slug>-<half>.yaml extend the third sweep pass
  for three models and add upstream's summarize_context stage, with this
  pack, for the cpp -> tt direction only. Since task P17.21 a template set
  serves context packs, so the runner's prompt and context checks accept
  each; without the generated pack the loader refuses each, naming the
  pack's generator.

Tests of the generated fragments skip when the pack has not been generated
in this checkout (uv run tools/build_tt_context.py --tree <tt-metal tree>).
Synthetic trees hold text written here. No value here is a measurement.
"""

