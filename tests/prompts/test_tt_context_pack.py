REPO = Path(__file__).resolve().parents[2]
PACK_NAME = "tt-metalium-5280a9cf"
PACK_DIR = REPO / "assets" / "context" / PACK_NAME
HEAD_SOURCE = f"assets/context/{PACK_NAME}.head.txt"
TEMPLATE_SOURCE = "assets/prompts/tt-host-v0/generate.txt"
MANIFEST = "MANIFEST.yaml"
GENERATOR = "tools/build_tt_context.py"
PIN = "5280a9cfb00998fd49667a29523d03aee905c129"
KEYS = ("metalium_guide.tt", "host_api.tt")
LIMIT_BYTES = 40 * 1024
CONTEXT_DIR = REPO / "projects" / "lassi-demo" / "context"
SWEEP3 = REPO / "projects" / "lassi-demo" / "sweep3"
SLUGS = ("qwen3-coder-30b", "exaone4-32b", "llama31-8b")
HALVES = ("maxabs", "pcc")
